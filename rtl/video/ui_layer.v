//=============================================================================
// ui_layer.v - 按钮层（UI 三件套之「图层表驱动」）
//-----------------------------------------------------------------------------
// 【在"扫描到哪算到哪"的架构里怎么做按钮】
//   本工程没有 framebuffer，每个像素是组合算出来的。按钮也一样：
//     (x,y) -> 落不落在某个按钮框里 -> 在的话画按钮色；被按下的那个换个颜色
//     (tx,ty) + pressed -> 落在哪个按钮里 -> 输出那个按钮的编号
//   全程组合，不引入流水线，不会让画面错位。
//
// 【为什么用"表"而不是一堆 if】
//   按钮的位置/尺寸/归属字段都放在 GLUT（一个常量数组）里。
//   加按钮、挪位置、改大小，只动表，不动判断逻辑。
//   综合时 for 循环会展开，每个按钮一套比较器，成本约 15 LUT/个。
//
// 【两个输出要分清楚】
//   draw/rgb : 【渲染】—— 这个像素属不属于按钮，是什么颜色
//   hit/hit_k: 【交互】—— 触摸点落在哪个按钮上（与渲染完全独立）
//   二者共用同一张表，所以"看到的"和"点到的"永远一致 ——
//   这一点很重要：如果分开写，很容易出现"框画在这里、热区在那里"的经典 bug。
//
// 【按钮怎么表达"我要改什么"】
//   每个按钮带一个 4 位的「动作码」act：
//     0..5  = 直接写 ui_ctrl 的某个寄存器地址（和 UART 命令同一个写法）
//     6..15  = 保留给"切换类"动作（代码里再解释）
//   这样上层的接线（uic_wr_addr = act）非常短，也不需要为每个按钮单独开线。
//=============================================================================
`timescale 1ns/1ps

// 布局常数（把手位置等）来自 disp_cfg.vh —— 布局的唯一真相源
`include "disp_cfg.vh"

module ui_layer #(
    parameter integer NB    = 6,        // 按钮个数
    parameter integer XW    = 10,       // 坐标位宽（与时序发生器一致）
    parameter integer YW    = 9,

    //--------------------- 按钮带的位置 ---------------------
    parameter integer BX0   = 0,        // 按钮带左上角（x 固定）
    parameter integer BY0   = 234,      // 按钮带【展开后】的 y（运行时由 ui_by0 覆盖）
    parameter integer BW    = 78,       // 每个按钮宽
    parameter integer BH    = 38,       // 高
    parameter integer GAP   = 0,        // 按钮之间的空隙

    //--------------------- 配色 ---------------------
    parameter [23:0] C_FACE  = 24'h20_40_60,   // 按钮底面
    parameter [23:0] C_EDGE  = 24'h60_A0_C0,   // 边框
    parameter [23:0] C_PRESS = 24'hC0_E0_FF,   // 被按下时的底面
    parameter [23:0] C_ACT   = 24'h30_60_90,   // 当前生效的那个按钮的底面
    parameter [23:0] C_TXT   = 24'hE0_F0_FF,   // 标签文字（底面之上）
    parameter [23:0] C_TXT_HI= 24'h10_20_30,   // 标签文字（按下/生效时用深色）

    //---- 展缩把手（侧边小三角）----
    parameter integer TX    = `DISP_TAB_X,
    parameter integer TY    = `DISP_TAB_Y,
    parameter integer TW    = `DISP_TAB_W,
    parameter integer TH    = `DISP_TAB_H,
    parameter [23:0] C_TAB  = 24'h38_78_A0     // 把手颜色
) (
    //--------------------- 扫描位置（组合） ---------------------
    input  wire [XW-1:0]  x,
    input  wire [YW-1:0]  y,

    //--------------------- 触摸状态 ---------------------
    //   tx/ty 是【屏幕坐标】（已经过校准换算），不是原始 ADC 值
    input  wire [XW-1:0]  tx,
    input  wire [YW-1:0]  ty,
    input  wire           pressed,      // 手指正按着

    //--------------------- 按钮带的实际 y（运行时） ---------------------
    //   展开/收起动画就是把它从「屏幕外」平滑移到 BY0。
    //   渲染和命中都只用这一个值 —— 不然会出现"框在这儿、热区在那儿"。
    input  wire [YW-1:0]  ui_by0,

    //--------------------- 面板是否展开（决定箭头方向） ---------------------
    input  wire           ui_open,

    //--------------------- 当前生效的按钮（用来画高亮） ---------------------
    input  wire [3:0]     active,       // 与某个按钮的 act 相同则高亮；其它值无高亮

    //--------------------- 渲染输出 ---------------------
    output reg            draw,         // 该像素属于按钮带（要盖住背景）
    output reg  [23:0]    rgb,

    //--------------------- 交互输出 ---------------------
    output reg  [2:0]     hit_k,        // 被按下的按钮编号（0..NB-1）
    output reg            hit,          // 有按钮被按下
    output wire [3:0]     hit_act,      // 被按下按钮的动作码

    //--------------------- 交互输出：把手 ---------------------
    output reg            tab_hit       // 手指正点在把手上
                                        //   （"按下那一拍"的边沿检测放在上层，
                                        //    因为上层才需要那个脉冲去翻转 ui_open）
);

    //=========================================================================
    // 按钮表
    //   name 只是给人看的，不参与逻辑；位置在 for 循环里用下标算。
    //   布局：底部一条，从左到右。
    //=========================================================================
    //   编号  动作码(act)  含义（由上层解释）
    //    0      0x0        VIEW   切换视图预设
    //    1      0x1        STYLE  柱体风格
    //    2      0x2        HUESPD 色相速度
    //    3      0x3        WAVEG  波形增益
    //    4      0x4        BGMODE 背景模式
    //    5      0x6        DEMO   演示图案
    reg [3:0] act_tab [0:NB-1];

    integer i;
    initial begin
        for (i = 0; i < NB; i = i + 1) act_tab[i] = i[3:0];
        if (NB > 5) act_tab[5] = 4'h6;      // 第 6 个按钮对应 DEMO 寄存器
    end

    //=========================================================================
    // 0. 按钮标签
    //-----------------------------------------------------------------------------
    //   每个按钮 8 个字符（不足补空格），从左起第 1 个字符格开始（x0+8）。
    //   8 字符 x 8 像素 = 64 px，按钮宽 78，所以左边留 8、右边留 6，基本居中。
    //
    //   为什么要"预先补好空格"而不是运行时算居中：
    //     算居中要除法，而且每个标签长度不同；直接把空格写进表里最省事，
    //     也一眼能看出屏幕上会排成什么样。
    //
    //   字库复用 rtl/video/font_rom.v（脚本生成的那份）。
    //=========================================================================
    localparam integer LBL_COL0 = 1;    // 标签从第几个字符格开始
    localparam integer LBL_NCH  = 8;    // 每个按钮放几个字符
    localparam integer LBL_ROWOFF = 2;  // 标签从第几个字符行开始（垂直居中）

    reg [7:0] lbl [0:NB*LBL_NCH-1];

    initial begin
        // 先把整张表填成空格，再覆盖有字的地方 —— 免得漏填时读出 X
        for (i = 0; i < NB*LBL_NCH; i = i + 1) lbl[i] = 8'h20;
        //          01234567
        lbl[ 0*8+0] = " "; lbl[ 0*8+1] = "V"; lbl[ 0*8+2] = "I";
        lbl[ 0*8+3] = "E"; lbl[ 0*8+4] = "W"; lbl[ 0*8+5] = " ";
        lbl[ 0*8+6] = " "; lbl[ 0*8+7] = " ";

        lbl[ 1*8+0] = "S"; lbl[ 1*8+1] = "T"; lbl[ 1*8+2] = "Y";
        lbl[ 1*8+3] = "L"; lbl[ 1*8+4] = "E"; lbl[ 1*8+5] = " ";
        lbl[ 1*8+6] = " "; lbl[ 1*8+7] = " ";

        lbl[ 2*8+0] = " "; lbl[ 2*8+1] = " "; lbl[ 2*8+2] = "H";
        lbl[ 2*8+3] = "U"; lbl[ 2*8+4] = "E"; lbl[ 2*8+5] = " ";
        lbl[ 2*8+6] = " "; lbl[ 2*8+7] = " ";

        lbl[ 3*8+0] = " "; lbl[ 3*8+1] = "G"; lbl[ 3*8+2] = "A";
        lbl[ 3*8+3] = "I"; lbl[ 3*8+4] = "N"; lbl[ 3*8+5] = " ";
        lbl[ 3*8+6] = " "; lbl[ 3*8+7] = " ";

        lbl[ 4*8+0] = " "; lbl[ 4*8+1] = " "; lbl[ 4*8+2] = "B";
        lbl[ 4*8+3] = "G"; lbl[ 4*8+4] = " "; lbl[ 4*8+5] = " ";
        lbl[ 4*8+6] = " "; lbl[ 4*8+7] = " ";

        lbl[ 5*8+0] = " "; lbl[ 5*8+1] = "D"; lbl[ 5*8+2] = "E";
        lbl[ 5*8+3] = "M"; lbl[ 5*8+4] = "O"; lbl[ 5*8+5] = " ";
        lbl[ 5*8+6] = " "; lbl[ 5*8+7] = " ";
    end

    //=========================================================================
    // 1. 渲染：这个像素属不属于按钮带，属于的话是什么颜色
    //=========================================================================
    reg in_band;
    reg [2:0] bx;               // 像素落在第几个按钮里

    always @(*) begin
        in_band = 1'b0;
        bx      = 3'd0;

        // 先判有没有落在整条带子里（省掉大部分比较）
        //   ⚠️ x 和 y 都要判！第一版只判了 y，结果最后一个按钮右边
        //      一直到屏幕右边缘都被当成"在带子里"，画出一条多余的色带。
        //      TB 的 [1] 抓到了（它专门扫了带子右侧）。
        // 写法说明：不要写成 `x >= BX0 && x < BX0 + ...`。
        //   因为 x 是无符号、BX0 通常是 0，`x >= 0` 恒真 —— Verilator 会报
        //   [UNSIGNED] Comparison is constant due to unsigned arithmetic
        //   （这个警告不在白名单里，会被门禁拦下，是它先发现这个问题的）。
        //   改成"先减再比"就自然安全：x < BX0 时相减下溢成一个很大的数，
        //   比较为假，效果正确，而且省掉一个比较器。
        if (y >= ui_by0 && y < (ui_by0 + BH) &&
            ((x - BX0[XW-1:0]) < (NB*(BW+GAP) - GAP)))
            in_band = 1'b1;

        // 再算落在第几个按钮里
        for (i = 0; i < NB; i = i + 1) begin
            if (x >= (BX0 + i*(BW+GAP)) && x < (BX0 + i*(BW+GAP) + BW))
                bx = i[2:0];
        end
    end

    // 边框：离按钮边缘 2 像素以内算边
    wire [XW-1:0] bx0 = BX0 + bx*(BW+GAP);
    wire [XW-1:0] off = x - bx0[XW-1:0];
    wire [YW-1:0] oy  = y - ui_by0;

    // 这个像素对应哪个字符格的哪一行
    wire [XW-1:0] lx = (x - bx0[XW-1:0]) >> 3;   // 字符列（含 LBL_COL0 偏移）
    wire [YW-1:0] ly = (oy - (LBL_ROWOFF*8)) >> 3;   // 字符行

    // ⚠️ 行范围必须【正好】是 7 行（oy 在 [ROWOFF*8, ROWOFF*8+7]）。
    //   第一版写成 `ly < 7`（ly 是字符格序号），范围宽到 oy=16..71，
    //   而字形行用的是 oy[2:0] 每 8 像素循环一次 —— 于是字母被【重复画了 8 遍】，
    //   一直画到按钮底部，连"避开标签取色"的配色判据都被顶掉了。
    wire        l_in  = in_band && (lx >= LBL_COL0[XW-1:0]) &&
                        (lx < (LBL_COL0 + LBL_NCH)) &&
                        (oy >= (LBL_ROWOFF*8)) && (oy < (LBL_ROWOFF*8 + 7));
    wire [2:0]  l_col = lx[2:0] - LBL_COL0[2:0];      // 0..7
    wire [7:0]  l_ch  = lbl[bx*LBL_NCH + l_col];

    // ⚠️ 查字库用的行号是【格内第几行】= oy[2:0]，不是 ly[2:0]。
    //   ly 是"按钮里第几个字符格"（38 px 高只会有 0/1/2），拿它当字形行的话
    //   7 行字形只显示了 3 行 —— 字母全变成竖条纹。
    //   这个 bug 是"把图导出来看一眼"才发现的：TB 的标签判据只数了亮点个数，
    //   条纹的亮点数一样多，所以它通过了。（和账本第 71 条同一类教训。）
    wire [7:0]  l_bits;
    font_rom #(.GW(5)) u_lbl_font (
        .ch  (l_ch),
        .row (oy[2:0]),
        .bits(l_bits)
    );

    // 字形取位：bit4 = 最左。格内列 = x[2:0]
    wire [7:0] l_shift = l_bits >> (4 - x[2:0]);
    wire       l_pix   = l_in && (x[2:0] < 5) && l_shift[0];

    wire is_edge = in_band &&
                   ((off < 2) || (off >= (BW-2)) ||
                    (oy  < 2) || (oy  >= (BH-2)));

    // 这个按钮当前是不是"生效中"（active 与它的动作码相同）
    wire is_active = (act_tab[bx] == active[3:0]);

    // 这个按钮当前是不是"被手指按着"
    wire is_pressed = pressed && hit && (hit_k == bx);

    //=========================================================================
    // 1b. 展缩把手（侧边小三角）
    //-----------------------------------------------------------------------------
    //   三角形宽 5、高 7，居中放在 TW x TH 的方框里。
    //   第 r 行的宽度 = 5 - |r-3|  ->  2,3,4,5,4,3,2（r=0..6）
    //   折叠时朝右（▶，像素靠左），展开时朝左（◀，像素靠右）。
    //
    //   把手【常驻显示】，不像按钮带那样会滑走 —— 否则收起后就再也点不开了。
    //=========================================================================
    wire [XW-1:0] tx_off = x - TX[XW-1:0];
    wire [YW-1:0] ty_off = y - TY[YW-1:0];

    wire in_tab = (x >= TX[XW-1:0]) && (x < (TX + TW)) &&
                  (y >= TY[YW-1:0]) && (y < (TY + TH));

    // 三角形：把 (tx_off, ty_off) 映射到 5x7 的三角区域
    wire [XW-1:0] tri_x = tx_off - ((TW - 5) / 2);      // 水平居中
    wire [YW-1:0] tri_y = ty_off - ((TH - 7) / 2);      // 垂直居中
    wire [2:0]    tri_r = tri_y[2:0];
    wire [3:0]    tri_w = 4'd5 - ((tri_r > 3'd3) ? (tri_r - 3'd3) : (3'd3 - tri_r));
    // ▶：像素靠左（0 .. w-1）；◀：像素靠右（5-w .. 4）
    wire [3:0]    tri_lo = ui_open ? (4'd5 - tri_w) : 4'd0;
    wire [3:0]    tri_hi = ui_open ? 4'd4 : (tri_w - 1'b1);

    wire tri_pix = in_tab && (tri_y < 7) &&
                   (tri_x >= tri_lo) && (tri_x <= tri_hi) &&
                   (tri_r < 7);

    always @(*) begin
        if (tri_pix) begin
            draw = 1'b1;
            rgb  = C_TAB;
        end else if (in_tab) begin
            // 把手底板：压暗的背景，让三角看得清
            draw = 1'b1;
            rgb  = 24'h10_18_20;
        end else if (!in_band) begin
            draw = 1'b0;
            rgb  = 24'h000000;
        end else begin
            draw = 1'b1;
            if (is_edge)
                rgb = C_EDGE;
            else if (is_pressed)
                rgb = l_pix ? C_TXT_HI : C_PRESS;   // 按下时用深色字，对比强
            else if (is_active)
                rgb = l_pix ? C_TXT_HI : C_ACT;
            else
                rgb = l_pix ? C_TXT    : C_FACE;
        end
    end

    //=========================================================================
    // 2. 交互：触摸点落在哪个按钮上
    //   注意用的是 tx/ty，和渲染用的 x/y 是两回事 ——
    //   但共用同一张表的同一套边界判断（下面的 in_rect 函数）。
    //=========================================================================
    function in_rect;
        input [XW-1:0] px;
        input [YW-1:0] py;
        input integer  k;
        reg   [XW-1:0] x0;
        begin
            x0 = BX0 + k*(BW+GAP);
            // 同样用"先减再比"，避开"px >= 常数 0 恒真"的无符号警告
            in_rect = ((px - x0) < BW) &&
                      (py >= ui_by0) && (py < (ui_by0 + BH));
        end
    endfunction

    reg [2:0] tk;
    reg       tv;

    always @(*) begin
        tk = 3'd0;
        tv = 1'b0;
        for (i = 0; i < NB; i = i + 1) begin
            if (in_rect(tx, ty, i)) begin
                tk = i[2:0];
                tv = 1'b1;
            end
        end
    end

    always @(*) begin
        hit   = pressed && tv;
        hit_k = tk;
    end

    // 把手命中：和渲染共用同一套几何（TX/TY/TW/TH）
    always @(*) begin
        tab_hit = pressed &&
                  (tx >= TX[XW-1:0]) && (tx < (TX + TW)) &&
                  (ty >= TY[YW-1:0]) && (ty < (TY + TH));
    end

    // ⚠️ hit_act 的语义是【正在被按下的按钮】，不是"光标停在哪个按钮上"！
    //   必须用 hit 门控，没按时返回 4'hF。
    //
    //   第一版写成 `assign hit_act = act_tab[tk];` —— 于是只要光标停在某个按钮上，
    //   动作码就一直有效。上层用"从 0xF 变成非 0xF"来判"按下"，
    //   而演示扫描的光标是【在按钮之间直接跳】的，从不经过 0xF，
    //   结果除了第一次，后面每一次"按下"都触发不了 ——
    //   现象是光标一直循环、配置一动不动。
    //
    //   写成连续赋值而不是放进 always @(*)：
    //   数组下标读取会让 iverilog 抱怨
    //   "@* is sensitive to all 6 words in array 'act_tab'"（功能上没错）。
    assign hit_act = hit ? act_tab[tk] : 4'hF;

endmodule
