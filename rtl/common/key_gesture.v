//=============================================================================
// key_gesture.v —— 把按键的"按了一下"翻译成【单击】/【双击】
//=============================================================================
// 【为什么需要它】
//   板子上只有两个按键（KEY1/KEY2），但要表达四种动作：
//       KEY1 单击 = 光标左移   KEY1 双击 = 面板开/关
//       KEY2 单击 = 光标右移   KEY2 双击 = 确认
//   于是必须用"单击 vs 双击"来区分。而这两者在【按下的那一瞬间是分不清的】——
//   必须等一个窗口，看窗口内还有没有第二下。
//
// 【时序：为什么单击要等】
//
//       第一次按下                      第二次按下
//           │                              │
//       ────┼────────── WIN_MS ────────────┼──────
//           │
//           │← 窗口内又按下 ⟹ 发 dbl（并且【绝对不发】single）
//           └─ 窗口期满都没再按 ⟹ 这时才发 single
//
//   ⟹ 所以"单击"有 WIN_MS 的延迟。这是【物理上不可避免的】：
//      不等待就分不清"这是单击"还是"这是双击的第一下"。
//      （鼠标默认双击间隔 500ms，触摸屏常用 300ms。）
//   ⟹ 反过来说：如果哪个方案声称"单击零延迟 + 双击也识别"，
//      它一定是把"双击的第一下"也当成了单击 —— 那是错的。
//
// 【接口约定】
//   press 是【消抖之后的单拍脉冲】（key_debounce 的 press 输出），
//   【不是电平】。所以本模块：
//     · 不需要再消抖
//     · 不会被"按住不放"影响（按住只会在按下沿产生一个脉冲）
//   ⟹ 这个约定很重要：如果哪天有人把电平接进来，按住会先出 single
//      再出 dbl。文档写在这里，免得踩。
//
// 【设计纪律（来自问题账本）】
//   · 只有一个 always 块写 状态/计数器/输出 —— 避免同拍读写竞态（账本 140/148/161）
//   · 所有寄存器都在复位里赋确定值（账本 132：`~X` 还是 X，自反馈寄存器会卡死）
//   · 输出是"默认拉低 + 显式置高一拍"——保证严格单拍脉冲
//=============================================================================
`default_nettype none

module key_gesture #(
    parameter integer CLK_HZ = 48_000_000,   // 时钟频率（Hz）
    parameter integer WIN_MS = 300           // 双击判定窗（毫秒）
) (
    input  wire clk,
    input  wire rst_n,

    input  wire press,      // 消抖后的"按了一下"（单拍脉冲，高有效）
    output reg  single,     // 单击（窗口期满后才发，严格单拍）
    output reg  dbl         // 双击（严格单拍）
);

    // 窗口长度（时钟拍数）。下限保护成 2，否则状态机没有"等待"的余地。
    localparam integer WIN_RAW = (CLK_HZ / 1000) * WIN_MS;
    localparam integer WIN_CYC = (WIN_RAW < 2) ? 2 : WIN_RAW;
    localparam integer CW      = $clog2(WIN_CYC + 1);

    localparam S_IDLE = 1'b0,
               S_WAIT = 1'b1;

    reg          st;
    reg [CW-1:0] cnt;

    always @(posedge clk) begin
        if (!rst_n) begin
            st     <= S_IDLE;
            cnt    <= {CW{1'b0}};
            single <= 1'b0;
            dbl    <= 1'b0;
        end else begin
            // ---- 输出默认拉低：下面只在需要的那一拍显式置 1 ----
            single <= 1'b0;
            dbl    <= 1'b0;

            case (st)
                //---------------------------------------------------------
                // 空闲：等"第一下"
                //---------------------------------------------------------
                S_IDLE: begin
                    cnt <= {CW{1'b0}};
                    if (press)
                        st <= S_WAIT;       // ⚠️ 先别发 single，等窗口
                end

                //---------------------------------------------------------
                // 等待窗：看窗口内还有没有第二下
                //---------------------------------------------------------
                S_WAIT: begin
                    if (press) begin
                        // 窗口内又按了一下 ⟹ 双击。
                        // ⚠️ 这里【绝不能】补发 single —— 双击不能带出单击。
                        //    这是本模块最容易写错的一行。
                        dbl <= 1'b1;
                        st  <= S_IDLE;
                    end else if (cnt == WIN_CYC[CW-1:0] - 1'b1) begin
                        // 窗口期满，确认是单击
                        single <= 1'b1;
                        st     <= S_IDLE;
                    end else begin
                        cnt <= cnt + 1'b1;
                    end
                end

                default: st <= S_IDLE;
            endcase
        end
    end

endmodule

`default_nettype wire
