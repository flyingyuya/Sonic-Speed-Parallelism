//=============================================================================
// env_track.v - 包络跟踪 + 自适应触发门限
//-----------------------------------------------------------------------------
// 【解决什么问题】
//   wave_buf 的触发条件是"信号先低于 -TH 再向上过零"，
//   而 TH 原来是【固定值】（满量程的 1/64）。
//   这带来两个麻烦：
//
//     ① 信号整体偏弱（比如音量小）  -> 永远碰不到 -TH
//        -> 迟滞闸门永远打不开 -> 只能靠自动触发兜底 -> 画面一直跳
//     ② 信号很强（接近满量程）      -> TH 相对太小，噪声也能骗过迟滞
//        -> 触发时刻抖，画面不稳
//
//   把 TH 变成"信号包络的一个比例"，两个问题一起解决：
//       小信号 -> 门限跟着变小，照样能触发
//       大信号 -> 门限跟着变大，噪声骗不过去
//
// 【为什么一定要有下限 TH_MIN】
//   门限 = 包络/8。静音时包络 -> 0，门限也 -> 0，
//   此时"信号低于 -TH"退化成"信号 < 0"，任何一点底噪都能满足
//   -> 触发时刻完全随机 -> 画面疯狂抖。
//   这是自适应门限最典型的坑，所以必须有 TH_MIN 兜底。
//
// 【包络怎么算：快攻 + 慢放（指数，不用乘法器）】
//
//        上升时：env <- env + (|x| - env) >> AS     （AS 小 -> 跟得快）
//        下降时：env <- env - (env >> DS)           （DS 大 -> 放得慢）
//
//   · 为什么用【指数】而不是线性加减：
//     线性衰减在 env 小于步长时会【永远停住】，再也回不到 0
//     （spectrum.v 里峰值保持就踩过这个，那里加了专门的判断）。
//     指数衰减 env - env>>DS 天然会趋向 0，不需要额外处理。
//   · 为什么"快攻慢放"：
//     攻击慢的话，一个大瞬态过去后门限要很久才追上 -> 期间触发不了；
//     释放快的话，门限会跟着波形的每一个周期上下抖 -> 门限本身在抖，
//     触发点自然跟着抖。所以必须是"立刻跟上去、慢慢放下来"。
//
//   时间常数：攻击 ~2^AS 个采样，释放 ~2^DS 个采样。
//   AS=6 -> 64 采样 = 1.3 ms；DS=12 -> 4096 采样 = 85 ms @48kHz。
//
// 【零 DSP】
//   整个模块只有：取绝对值（取反+1）、两个移位、两个加/减法，没有乘法器。
//=============================================================================
`timescale 1ns/1ps

module env_track #(
    parameter integer DW     = 24,      // 采样位宽
    parameter integer AS     = 6,       // 攻击速率（越小跟得越快）
    parameter integer DS     = 12,      // 释放速率（越大放得越慢）
    parameter integer KP     = 3,       // 门限 = 包络 >> KP
    // 门限下限。4096 = 2^12 = 满量程的 1/2048。
    //   太小挡不住底噪；太大则弱信号还是触发不了。这个值要按实测调。
    parameter integer TH_MIN = 4096
) (
    input  wire                 clk,
    input  wire                 rst_n,      // 同步复位（本项目惯例）
    input  wire                 en,         // 采样有效
    input  wire signed [DW-1:0] din,

    // 建议的触发门限（**正数**，表示幅度）。
    //   调用方拿它去跟 -th 比较。始终 >= TH_MIN。
    output reg  signed [DW-1:0] th,
    // 当前包络（调试/观察用，也可以在屏幕上显示出来）
    output reg         [DW-1:0] env
);

    // 多一位：|x| 在 x = -2^(DW-1) 时等于 2^(DW-1)，DW 位装不下
    localparam integer IW = DW + 1;

    localparam [IW-1:0] THMIN_L = TH_MIN;
    localparam [IW-1:0] ONE_L   = {{(IW-1){1'b0}}, 1'b1};

    //-------------------------------------------------------------------------
    // 取绝对值
    //-------------------------------------------------------------------------
    wire signed [IW-1:0] xin = {{1{din[DW-1]}}, din};
    wire        [IW-1:0] ax  = xin[IW-1] ? (~xin + ONE_L) : xin;

    //-------------------------------------------------------------------------
    // 包络：快攻 / 慢放
    //-------------------------------------------------------------------------
    reg [IW-1:0] env_r;

    // 都是无符号运算：上行时 ax >= env_r，差是正的
    wire [IW-1:0] e_up   = env_r + ((ax - env_r) >>> AS);
    wire [IW-1:0] e_down = env_r - (env_r >>> DS);

    wire [IW-1:0] env_nxt = (ax >= env_r) ? e_up : e_down;

    //-------------------------------------------------------------------------
    // 门限 = 包络 >> KP，并夹到 TH_MIN 以上
    //-------------------------------------------------------------------------
    wire [IW-1:0] th_raw = env_nxt >>> KP;
    wire [IW-1:0] th_nxt = (th_raw < THMIN_L) ? THMIN_L : th_raw;

    always @(posedge clk) begin
        if (!rst_n) begin
            env_r <= {IW{1'b0}};
            th    <= {DW{1'b0}};
            env   <= {DW{1'b0}};
        end else if (en) begin
            env_r <= env_nxt;
            // 门限只取 DW 位。因为 th_raw <= env <= 2^(DW-1)，不会溢出。
            th    <= th_nxt[DW-1:0];
            // ⚠️ 这里是 env_nxt 不是 env_r —— 要和 th 用【同一个】包络值，
            //    否则 env 比 th 晚一拍，调试时看着永远对不上（账本里
            //    "和被测信号差一拍"这一族已经栽过好几次）。
            env   <= env_nxt[DW-1:0];
        end
    end

endmodule
