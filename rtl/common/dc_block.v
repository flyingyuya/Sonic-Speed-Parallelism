//=============================================================================
// dc_block.v - 直流阻断器（一阶高通 / DC blocker）
//-----------------------------------------------------------------------------
// 差分方程：
//
//     y[n] = x[n] - x[n-1] + y[n-1] * (1 - 2^-SH)
//
// 展开就是常见的那条"DC blocker"：
//
//     y[n] = x[n] - x[n-1] + y[n-1] - (y[n-1] >>> SH)
//
// 【为什么要它】
//   音频 ADC 输出带直流偏置（模数转换器自己的失调、前端耦合电容等）。
//   对显示来说有【两个】具体危害：
//
//     ① 波形不居中   零点不在屏幕中线上
//     ② 触发不了     ← 这个才是真麻烦
//        wave_buf 用的是"信号先低于 -TH，再向上过零"的迟滞触发。
//        如果直流偏置 D 比信号幅度 A 还大，信号【永远到不了负半周】，
//        迟滞闸门永远打不开 -> 只能靠"自动触发"兜底 -> 画面一直跳。
//
//   把直流拿掉之后，信号天然围绕 0 对称，两个问题一起解决。
//
// 【为什么把它放在显示通路上，而不是音频通路上】
//   放音频主通路上会改动已经逐位验证过的 EQ / 频谱行为（blame 范围变大）。
//   而它要解决的问题只和"波形显示 + 触发"有关，所以就插在
//   audio_top.rx_l -> 波形 mux 之间（见 rtl/top.v）。
//   以后要是想让声音也去掉直流，把它挪到 audio_top 后面即可，模块本身不用动。
//
// 【零 DSP：为什么不用乘法器】
//   系数取 R = 1 - 2^-SH，于是 R*y 变成 "y - (y >>> SH)"，
//   一个移位 + 一个减法。SH 越大 -> 极点越靠近 1 -> 截止频率越低。
//
//   截止频率    f_c ≈ (1-R) * fs / (2*pi) = 2^-SH * fs / (2*pi)
//   SH=10, fs=48kHz -> f_c ≈ 7.46 Hz
//   时间常数    tau = 2^SH / fs = 1024 / 48000 ≈ 21.3 ms
//
// 【位宽与溢出】
//   内部用 DW+GW 位。该滤波器在奈奎斯特附近的增益只有
//       2 / (1+R) = 2 / (2 - 2^-SH) ≈ 1.0005
//   也就是"几乎不放大"，所以 GW=2（四倍余量）足够。
//   输出再按 DW 位做【饱和】，不做回绕 —— 回绕在波形上表现为突然
//   从正满幅跳到负满幅，非常刺眼；饱和只是削平，视觉上可接受。
//
// 【为什么不做舍入】
//   `>>>` 是算术右移（向 -inf 取整），严格说会引入一点点直流。
//   算一下量级：环路稳定条件是 y[n] = y[n-1]，即 (y >>> SH) = 0，
//   所以稳态残差 |y| < 2^SH = 1024（这是 DW+GW 位下的 LSB）。
//   折算到 24 位输出是 1024/4 = 256 个 LSB，占满量程 256/2^23 ≈ 0.003%。
//   映射到屏幕振幅（22 px）上不到 0.001 px，完全看不见。
//   省下一个加法器、缩短反馈路径（y -> 加 -> 加 -> y）更划算。
//=============================================================================
`timescale 1ns/1ps

module dc_block #(
    parameter integer DW = 24,      // 输入/输出位宽
    parameter integer SH = 10,      // R = 1 - 2^-SH
    parameter integer GW = 2        // 内部保护位
) (
    input  wire                 clk,
    input  wire                 rst_n,      // 同步复位（本项目惯例）
    input  wire                 en,         // 采样有效（每个采样一个 strobe）
    input  wire signed [DW-1:0] din,
    output reg  signed [DW-1:0] dout
);

    localparam integer IW = DW + GW;

    // 24 位有符号的边界（用于输出饱和）
    localparam signed [DW-1:0] V_MAX = {1'b0, {(DW-1){1'b1}}};
    localparam signed [DW-1:0] V_MIN = {1'b1, {(DW-1){1'b0}}};

    reg signed [IW-1:0] x1;     // x[n-1]
    reg signed [IW-1:0] y;      // y[n-1]

    // 符号扩展到内部位宽
    wire signed [IW-1:0] xin = {{GW{din[DW-1]}}, din};

    // y[n-1] * R = y - (y >>> SH)
    wire signed [IW-1:0] ysh   = y >>> SH;

    // ⚠️ 反馈路径是 y -> (xin - x1 + y) -> (- ysh) -> y，两级加法器。
    //    xin - x1 不在反馈环上，可以和它并行算，所以关键路径只有 2 个加法器。
    wire signed [IW-1:0] ynext = xin - x1 + y - ysh;

    // 输出要不要饱和：内部值能否用 DW 位有符号表示
    wire y_ovf = (y[IW-1:DW] != {(IW-DW){y[DW-1]}});

    always @(posedge clk) begin
        if (!rst_n) begin
            x1   <= {IW{1'b0}};
            y    <= {IW{1'b0}};
            dout <= {DW{1'b0}};
        end else if (en) begin
            x1 <= xin;
            y  <= ynext;

            // ⚠️ 饱和方向看的是【内部最高位】y[IW-1]，不是 y[DW-1]。
            //    负溢出时 y[DW-1] 可能是 0（比如 -2^24 的 24 位截断是 0），
            //    用它判方向会 saturate 到 +V_MAX，反了。
            if (y_ovf) dout <= y[IW-1] ? V_MIN : V_MAX;
            else       dout <= y[DW-1:0];
        end
    end

endmodule
