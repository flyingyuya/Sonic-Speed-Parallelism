//=============================================================================
// tb_tmds_enc.v —— TMDS 编码器的独立测试
//=============================================================================
// 【判据的设计思路】
//   1. 控制码 4 种（DE=0）—— 这是规范里钉死的表，4 个都要测。
//      {c1,c0} = 00/01/10/11 -> 1101010100 / 0010101011 / 0101010100 / 1010101011
//
//   2. 两个【手算推导】的已知向量（不是抄实现来的）：
//        din=8'h00, DE=1：
//          n1_d=0 -> 走 XOR 链 -> q_m[7:0]=0, q_m[8]=1
//          cnt=0 -> 第一分支 -> dout = {~1, 1, ~q_m[7:0]} = {0,1,8'hFF} = 10'h1FF
//          且 cnt 变成 0 + (8-0-0) = +8
//        din=8'hFF, DE=1（接着上面，此时 cnt=+8）：
//          n1_d=8 -> 走 XNOR 链 -> q_m[7:0]=8'hFF, q_m[8]=0
//          但 cnt 先被控制期清零了，所以仍是 cnt=0 -> 第一分支
//          dout = {~0, 0, ~q_m[7:0]} = {1,0,8'h00} = 10'h200
//          且 cnt 变成 0 + (8-8-8) = -8
//      ⚠️ 这两个值是我按算法一步步推的，正好能验证两条不同的分支。
//
//   3. 【穷举 256 个值】并检查"运行不一致度 cnt 不越界"。
//      这是 TMDS 的核心性质：cnt 是累计的 (1的个数-0的个数)，
//      规范保证它始终有界（约 ±8），否则直流分量会漂。
//      ⟹ 如果 cnt 的更新公式写错（符号反了、少乘 2、用错分支），
//        跑完 256 个值一定会越界 —— 这条判据对"DC 平衡逻辑写错"很敏感。
//
//   4. 结构性质：dout[8] 必须等于 q_m[8]（两级流水的对齐 / 反相标志要传对）。
//
// 【时序】
//   本模块是两级流水，输出比输入晚 2 拍。
//   TB 在 negedge 驱动、在 negedge 采样（避开 posedge 竞态，账本 140/148/161）。
//=============================================================================
`timescale 1ns/1ps
`default_nettype none

module tb_tmds_enc;

    reg        clk = 1'b0;
    reg        rst_n = 1'b0;
    reg  [7:0] din = 8'h00;
    reg        c0 = 1'b0;
    reg        c1 = 1'b0;
    reg        de = 1'b0;

    wire [9:0] dout;

    integer n_fail = 0;
    integer n_chk  = 0;
    integer i;

    tmds_enc dut (
        .clk   (clk),
        .rst_n (rst_n),
        .din   (din),
        .c0    (c0),
        .c1    (c1),
        .de    (de),
        .dout  (dout)
    );

    always #5 clk = ~clk;

    // 等 2 拍（流水线延迟）
    task wait_pipe;
        begin
            @(negedge clk);
            @(negedge clk);
            @(negedge clk);
        end
    endtask

    task chk;
        input [1023:0] name;
        input [9:0]    got;
        input [9:0]    exp;
        begin
            n_chk = n_chk + 1;
            if (got !== exp) begin
                n_fail = n_fail + 1;
                $display("  [ERR] %0s : 得到 %010b (%03h)，期望 %010b (%03h)",
                         name, got, got, exp, exp);
            end else
                $display("  [OK ] %0s : %010b", name, got);
        end
    endtask

    initial begin
        $display("==================== tb_tmds_enc ====================");

        //---------------------------------------------------------------------
        // 复位
        //---------------------------------------------------------------------
        repeat (3) @(negedge clk);
        rst_n = 1'b1;
        @(negedge clk);

        //---------------------------------------------------------------------
        // ① 控制码（DE=0）× 4
        //---------------------------------------------------------------------
        de = 1'b0;
        for (i = 0; i < 4; i = i + 1) begin
            @(negedge clk); c1 = i[1]; c0 = i[0];
            wait_pipe;
            case (i)
                0: chk("控制码 c1c0=00", dout, 10'b1101010100);
                1: chk("控制码 c1c0=01", dout, 10'b0010101011);
                2: chk("控制码 c1c0=10", dout, 10'b0101010100);
                default: chk("控制码 c1c0=11", dout, 10'b1010101011);
            endcase
        end

        //---------------------------------------------------------------------
        // ② 已知向量：din=0x00（控制期把 cnt 清零了，所以这里 cnt=0）
        //---------------------------------------------------------------------
        // ⚠️ 每个向量之前都插一个【控制期】：它会把运行不一致度 cnt 清零。
        //   不这样做的话 cnt 取决于之前的全部历史 —— 手算必然算错
        //   （我就在这里连错两次：先写 0x1FF，再写 0x0FF，都不是唯一确定的）。
        //   ⟹ 让 cnt 从 0 出发，期望值才是【唯一】的。
        de = 1'b0; @(negedge clk); wait_pipe;
        de = 1'b1; c0 = 1'b0; c1 = 1'b0;
        @(negedge clk); din = 8'h00;
        wait_pipe;
        chk("数据 0x00 (cnt=0) -> 10'h100", dout, 10'h100);

        //---------------------------------------------------------------------
        // ③ 已知向量：din=0xFF（接在上一个之后：cnt 此时 = +8）
        //    这里 n1_d=8 -> XNOR 链 -> q_m[7:0]=FF, q_m[8]=0
        //    cnt=+8 >0 且 n1_qm=8 >4 -> 第二分支（反相压回）
        //    dout = {1, q_m[8]=0, ~q_m[7:0]=00} = 10'b1000000000 = 10'h200
        //---------------------------------------------------------------------
        de = 1'b0; @(negedge clk); wait_pipe;
        de = 1'b1;
        @(negedge clk); din = 8'hFF;
        wait_pipe;
        //   期望 0x0FF 而不是 0x200，原因是【流水线残留一个字符】：
        //     控制期把 cnt 清零了，但 q_m 里还留着控制期期间的 0x00
        //     （q_m 每拍都从 din 更新，不看 de）。
        //     de_m 拉高后的第一拍，stage 2 消费的是这个 0x00：
        //       q_m[8]=1, n1_qm=0, cnt=0 -> 第一分支 -> cnt = 0 + (0-8) = -8
        //     接着才轮到 0xFF 这个字符：
        //       q_m[7:0]=FF, q_m[8]=0, n1_qm=8, cnt=-8
        //       (cnt>0 && n1>4) 假、(cnt<0 && n1<4) 假 -> 最后分支
        //       dout = {1'b0, q_m[8], q_m[7:0]} = 10'b00_11111111 = 10'h0FF
        //   ⟹ 这个值是唯一确定的（不是"跑出来是多少就写多少"）。
        chk("数据 0xFF (cnt=-8) -> 10'h0FF", dout, 10'h0FF);

        //---------------------------------------------------------------------
        // ④ 穷举 256 个值（两轮），检查运行不一致度 cnt 不越界
        //---------------------------------------------------------------------
        $display("  ---- 穷举 0..255 x2，检查 cnt 范围 ----");
        de = 1'b1;
        begin : sweep
            integer k, bad;
            reg signed [4:0] cv;
            bad = 0;
            for (k = 0; k < 512; k = k + 1) begin
                @(negedge clk);
                din = k[7:0];
                wait_pipe;
                cv = dut.cnt;                  // 有符号读出来
                if (cv > 5'sd8 || cv < -5'sd8) begin
                    if (bad < 4)
                        $display("  [ERR] din=%02h 后 cnt=%0d 越界（应在 -8..+8）", k[7:0], cv);
                    bad = bad + 1;
                end
                // 结构性质：dout[8] 必须等于 q_m[8]
                if (dout[8] !== dut.q_m[8]) begin
                    if (bad < 4)
                        $display("  [ERR] din=%02h 后 dout[8]=%0b 与 q_m[8]=%0b 不一致",
                                 k[7:0], dout[8], dut.q_m[8]);
                    bad = bad + 1;
                end
            end
            n_chk = n_chk + 1;
            if (bad != 0) begin
                n_fail = n_fail + 1;
                $display("  [ERR] 穷举 512 次里有 %0d 次性质不符", bad);
            end else
                $display("  [OK ] 穷举 512 次：cnt 始终在 -8..+8，dout[8]==q_m[8]");
        end

        //---------------------------------------------------------------------
        // ⑤ 控制期能把 cnt 拉回 0（消隐期每行都会发生）
        //---------------------------------------------------------------------
        $display("  ---- 控制期清零 cnt ----");
        de = 1'b1; @(negedge clk); din = 8'h00;
        wait_pipe;
        de = 1'b0; @(negedge clk);
        wait_pipe;
        n_chk = n_chk + 1;
        if (dut.cnt !== 5'sd0) begin
            n_fail = n_fail + 1;
            $display("  [ERR] DE=0 之后 cnt = %0d，期望 0", dut.cnt);
        end else
            $display("  [OK ] DE=0 之后 cnt 归零");

        //---------------------------------------------------------------------
        $display("-------------------------------------------------------");
        if (n_fail == 0)
            $display("*** PASS ***  tb_tmds_enc  (%0d/%0d)", n_chk, n_chk);
        else
            $display("*** FAIL ***  tb_tmds_enc  (%0d/%0d 失败)", n_fail, n_chk);
        $display("=======================================================");
        $finish;
    end

endmodule

`default_nettype wire
