//=============================================================================
// tb_key_gesture.v —— key_gesture（单击/双击识别）的独立测试
//=============================================================================
// 【测试设计要点】
//   1. 【在 negedge 驱动 press】—— 不要在 posedge 驱动。DUT 是 posedge 采样，
//      同一时间步里 TB 改输入 + DUT 采样 = 竞态（账本 140/148/161 踩过 3 次）。
//   2. 【在 negedge 数输出】—— DUT 的输出是 posedge 更新的，negedge 采样会偏一拍。
//   3. 窗口很小（CLK_HZ=1000, WIN_MS=5 ⟹ WIN_CYC=5），所以边界能手工算清楚。
//      这很关键：如果窗口是 14400000 拍，测试只能"差不多"地测，
//      而【边界恰好是这种模块唯一会错的地方】。
//
// 【窗口边界（WIN_CYC = 5）的精确含义】
//   进入 S_WAIT 那拍 cnt=0，随后每拍 +1，cnt==4 时发 single。
//   S_WAIT 里【先检查 press，再看超时】⟹
//       两次按下的间隔 ≤ 5 拍  ⟹ 双击（第 5 拍那次"压线"算双击）
//       间隔 ≥ 6 拍           ⟹ 两个单击
//   这两条都要测，否则"差一拍"的 bug 会漏过去。
//=============================================================================
`timescale 1ns/1ps
`default_nettype none

module tb_key_gesture;

    // ---- 让仿真跑得快：1 kHz 的"时钟"，窗口 5 ms = 5 拍 ----
    localparam integer CLK_HZ = 1000;
    localparam integer WIN_MS = 5;
    localparam integer WIN    = 5;      // WIN_CYC

    reg  clk = 1'b0;
    reg  rst_n = 1'b0;
    reg  press = 1'b0;

    wire single, dbl;

    integer n_single = 0;
    integer n_dbl    = 0;
    integer n_fail   = 0;
    integer n_chk    = 0;

    key_gesture #(
        .CLK_HZ (CLK_HZ),
        .WIN_MS (WIN_MS)
    ) dut (
        .clk    (clk),
        .rst_n  (rst_n),
        .press  (press),
        .single (single),
        .dbl    (dbl)
    );

    always #5 clk = ~clk;               // 10 ns 周期

    //-------------------------------------------------------------------------
    // 在 negedge 数脉冲（见文件头"测试设计要点"第 2 条）
    //-------------------------------------------------------------------------
    always @(negedge clk) begin
        if (rst_n) begin
            if (single) n_single = n_single + 1;
            if (dbl)    n_dbl    = n_dbl + 1;
        end
    end

    //-------------------------------------------------------------------------
    // 激励原语
    //-------------------------------------------------------------------------
    task do_reset;
        begin
            @(negedge clk);
            rst_n = 1'b0;
            press = 1'b0;
            @(negedge clk);
            @(negedge clk);
            rst_n = 1'b1;
            n_single = 0;
            n_dbl    = 0;
            @(negedge clk);
        end
    endtask

    // 发一个"按了一下"的【单拍脉冲】（模仿 key_debounce 的输出）
    task do_press;
        begin
            @(negedge clk);
            press = 1'b1;
            @(negedge clk);
            press = 1'b0;
        end
    endtask

    // 等待 n 个时钟（在 negedge 上数，避免和 DUT 抢 posedge）
    task wait_cyc;
        input integer n;
        integer i;
        begin
            for (i = 0; i < n; i = i + 1)
                @(negedge clk);
        end
    endtask

    //-------------------------------------------------------------------------
    // 检查
    //-------------------------------------------------------------------------
    task chk;
        input [1023:0] name;
        input integer exp_single;
        input integer exp_dbl;
        begin
            n_chk = n_chk + 1;
            if ((n_single == exp_single) && (n_dbl == exp_dbl)) begin
                $display("  [OK ] %0s : single=%0d dbl=%0d", name, n_single, n_dbl);
            end else begin
                n_fail = n_fail + 1;
                $display("  [ERR] %0s : 期望 single=%0d dbl=%0d，实际 single=%0d dbl=%0d",
                         name, exp_single, exp_dbl, n_single, n_dbl);
            end
        end
    endtask

    //-------------------------------------------------------------------------
    // 主流程
    //-------------------------------------------------------------------------
    integer i;

    initial begin
        $display("==================== tb_key_gesture ====================");
        $display("WIN_CYC = %0d 拍", WIN);

        //---------------------------------------------------------------------
        // 1. 单击：按一下，窗口期满后【恰好】一个 single
        //---------------------------------------------------------------------
        do_reset;
        do_press;
        // 按下后马上检查：此时还不该有任何输出（这就是"单击要等"的直接证据）
        wait_cyc(WIN - 1);
        chk("1.单击:窗口未满时【不能】提前发 single", 0, 0);
        wait_cyc(4);
        chk("1.单击:窗口期满后恰好一个 single", 1, 0);

        //---------------------------------------------------------------------
        // 2. 双击：★ 本模块存在的理由 —— 必须【只有 dbl，没有 single】
        //---------------------------------------------------------------------
        do_reset;
        do_press;
        wait_cyc(2);
        do_press;
        wait_cyc(WIN + 3);
        chk("2.双击:只有 dbl、【绝不能】带出 single", 0, 1);

        //---------------------------------------------------------------------
        // 3. 窗口边界（内侧）：两次按下的 posedge 间隔正好 = WIN_CYC = 5
        //    ⟹ 仍然算双击
        //
        //  ⚠️ 这里的 -2 是【画时序图画出来的】，不是凑出来的：
        //     do_press 自身占 2 个 negedge（置高那个 + 拉低那个），
        //     所以"想让它落在第 5 个 posedge 上"要等 WIN-2 个 negedge。
        //     第一版写 WIN-1 ⟹ 实际间隔 6 拍 ⟹ 得到 2 个单击，
        //     而 DUT 是对的。教训见账本 145/149/160：差一位时停下画图。
        //---------------------------------------------------------------------
        do_reset;
        do_press;
        wait_cyc(WIN - 2);
        do_press;
        wait_cyc(WIN + 3);
        chk("3.边界(内):间隔 5 拍仍算双击", 0, 1);

        //---------------------------------------------------------------------
        // 4. 窗口边界（外侧）：posedge 间隔 6 拍 ⟹ 两个单击
        //    （比 3 多等一个 negedge，就跨出了窗口 —— 这条和 3 一起，
        //      把"边界到底在哪一拍"钉死。）
        //---------------------------------------------------------------------
        do_reset;
        do_press;
        wait_cyc(WIN - 1);      // 间隔 6 拍
        do_press;
        wait_cyc(WIN + 3);
        chk("4.边界(外):间隔 6 拍变两个单击", 2, 0);

        //---------------------------------------------------------------------
        // 5. 两下隔很远（远超窗口）⟹ 两个单击
        //---------------------------------------------------------------------
        do_reset;
        do_press;
        wait_cyc(WIN * 4);
        do_press;
        wait_cyc(WIN + 3);
        chk("5.隔很远:两个单击", 2, 0);

        //---------------------------------------------------------------------
        // 6. 三连击：第 1+2 下 = 双击，第 3 下重新开始 = 单击
        //    （这是"定义"层面的事：连击怎么切分，必须钉死，否则将来会争）
        //---------------------------------------------------------------------
        do_reset;
        do_press;
        wait_cyc(2);
        do_press;
        wait_cyc(2);
        do_press;
        wait_cyc(WIN + 3);
        chk("6.三连击:1 个双击 + 1 个单击", 1, 1);

        //---------------------------------------------------------------------
        // 7. 窗口期内复位：不能留下"半个单击"
        //    这里同时验证账本 132 那条：自反馈寄存器忘了复位会卡死。
        //---------------------------------------------------------------------
        do_reset;
        do_press;
        wait_cyc(2);
        @(negedge clk); rst_n = 1'b0;       // 在 S_WAIT 中间复位
        @(negedge clk);
        @(negedge clk);
        rst_n = 1'b1;
        n_single = 0; n_dbl = 0;
        wait_cyc(WIN + 3);
        chk("7.窗口期内复位:不发 single、状态干净", 0, 0);

        // 复位后还能正常工作（证明状态机没卡死）
        do_press;
        wait_cyc(WIN + 3);
        chk("7b.复位后:单击功能正常", 1, 0);

        //---------------------------------------------------------------------
        // 8. 长时间空转：不能自己冒出脉冲
        //---------------------------------------------------------------------
        do_reset;
        wait_cyc(WIN * 6);
        chk("8.长时间无按键:输出保持安静", 0, 0);

        //---------------------------------------------------------------------
        $display("-------------------------------------------------------");
        if (n_fail == 0)
            $display("*** PASS ***  tb_key_gesture  (%0d/%0d)", n_chk, n_chk);
        else
            $display("*** FAIL ***  tb_key_gesture  (%0d/%0d 失败)", n_fail, n_chk);
        $display("=======================================================");
        $finish;
    end

endmodule

`default_nettype wire
